const DICT = { en: EN };
export const LANGS = ['id', 'en'];

let lang = 'id';
try {
  const saved = localStorage.getItem('kb-lang');
  lang = LANGS.includes(saved) ? saved : 'id';
} catch (_) {}

export const getLang = () => lang;
export const locale = () => (lang === 'en' ? 'en-US' : 'id-ID');

export function setLang(l) {
  if (!LANGS.includes(l)) return;
  lang = l;
  try { localStorage.setItem('kb-lang', l); } catch (_) {}
}

// t('Halo, {name}', { name: 'Budi' })
export function t(key, vars) {
  let s = (lang !== 'id' && DICT[lang]?.[key]) || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

